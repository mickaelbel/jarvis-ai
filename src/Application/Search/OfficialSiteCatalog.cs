    public static string HostMatchesDomain(string host, string domain)
    {
        if (string.IsNullOrWhiteSpace(host) || string.IsNullOrWhiteSpace(domain))
            return string.Empty;
        var h = host.ToLowerInvariant();
        var d = domain.ToLowerInvariant();
        if (h == d)
            return d;
        if (h.EndsWith("." + d, StringComparison.OrdinalIgnoreCase))
            return d;
        return string.Empty;
    }
