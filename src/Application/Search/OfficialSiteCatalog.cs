    public static bool IsMediaDomain(string host)
    {
        if (string.IsNullOrWhiteSpace(host))
            return false;
        var h = host.ToLowerInvariant();
        if (h.StartsWith("www.", StringComparison.Ordinal))
            h = h[4..];
        return MediaDomains.Contains(h);
    }

    public static string? FindMediaDomain(string host)
    {
        if (string.IsNullOrWhiteSpace(host))
            return null;
        var h = host.ToLowerInvariant();
        if (h.StartsWith("www.", StringComparison.Ordinal))
            h = h[4..];
        return MediaDomains.FirstOrDefault(m => OfficialSiteCatalog.HostMatchesDomain(h, m) == m);
    }

    public static bool IsDocsHost(string host)
    {
        if (string.IsNullOrWhiteSpace(host))
            return false;
        var h = host.ToLowerInvariant();
        return h.StartsWith("docs.", StringComparison.Ordinal) ||
               h == "learn.microsoft.com" ||
               h.EndsWith(".readthedocs.io", StringComparison.Ordinal) ||
               h.EndsWith(".github.io", StringComparison.Ordinal);
    }

